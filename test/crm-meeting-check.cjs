const assert = require('node:assert/strict');
const { project, dateKey } = require('../crm-meeting-model.js');
const company = (newMou = {}, corrections = {}) => ({ id: 'co-123', name: '검증업체', partnerDashboard: { newMou, stageCorrections: corrections } });
assert.equal(dateKey('26.10.19'), '2026-10-19');
assert.equal(dateKey('2026-02-30'), '');
assert.equal(dateKey('날짜 미정'), '');
const co = company({ m1ScheduledLabel: '26.10.19', m1ScheduledTime: '09:30', m2Scheduled: '2026-10-20', m2ScheduledTime: '14:00', qSentLabel: '26.10.10', mouLabel: '26.11.01' });
const before = JSON.stringify(co);
const rows = project([co]);
assert.equal(rows.length, 2);
assert.equal(rows[0].title, '검증업체 · 1차 미팅');
assert.equal(rows[0].time, '09:30');
assert.equal(rows[1].title, '검증업체 · 2차 미팅');
assert.equal(JSON.stringify(co), before, 'source data is never mutated');
assert.equal(project([co, co]).length, 2, 'stable company/stage identity prevents duplicates');
const changed = company({}, { m1Scheduled: { status: 'scheduled', dateText: '2026.10.22', timeText: '15:30' } });
assert.equal(project([changed])[0].id, rows[0].id, 'rescheduling retains one identity');
assert.equal(project([changed])[0].date, '2026-10-22');
assert.equal(project([changed])[0].time, '15:30');
assert.equal(project([company(co.partnerDashboard.newMou, { m1Scheduled: { status: 'none', dateText: '' } })]).length, 1, 'date deletion overrides original date');
assert.equal(project([company({ m1ScheduledLabel: '26.10.19', m1Done: true })]).length, 0);
assert.equal(project([company({ m1ScheduledLabel: '26.10.19', m1Label: '26.01.01' })]).length, 0);
assert.equal(project([company({}, { m1Scheduled: { status: 'done', dateText: '26.10.19' } })]).length, 0);
for (const extra of [{ deletedAt: '2026-10-01' }, { agreementInvalidated: { at: '2026-10-01' } }, { agreementStatus: 'terminated' }]) assert.equal(project([{ ...co, ...extra }]).length, 0);
assert.equal(project([company({ m1ScheduledLabel: '26.10.19', m1ScheduledTime: '99:99' })])[0].time, '');
assert.equal(project([company({ m1Label: '27.01.01' })], '2026-10-07')[0].date, '2027-01-01', 'legacy future meeting date remains scheduled');
assert.equal(project([]).length, 0, 'authoritative empty snapshot removes imported meetings');
assert.equal(project([null, {}, { id: 'x' }]).length, 0);
console.log('PASS: only first/second scheduled meetings; dates/times; stable IDs; updates/cancellation; completed/deleted exclusions; original data preserved');
